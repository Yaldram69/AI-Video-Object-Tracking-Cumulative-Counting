import cv2
import numpy as np
from ultralytics import YOLO
import random
from collections import defaultdict, Counter
# from google.colab.patches import cv2_imshow
import cv2

# Load YOLOv8 model (Pre-trained or fine-tuned)
model = YOLO("yolov8n.pt")

# COCO class names
COCO_CLASSES = [
    "person", "bicycle", "car", "motorcycle", "airplane", "bus", "train", "truck", "boat", "traffic light",
    "fire hydrant", "stop sign", "parking meter", "bench", "bird", "cat", "dog", "horse", "sheep", "cow",
    "elephant", "bear", "zebra", "giraffe", "backpack", "umbrella", "handbag", "tie", "suitcase", "frisbee",
    "skis", "snowboard", "sports ball", "kite", "baseball bat", "baseball glove", "skateboard", "surfboard",
    "tennis racket", "bottle", "wine glass", "cup", "fork", "knife", "spoon", "bowl", "banana", "apple",
    "sandwich", "orange", "broccoli", "carrot", "hot dog", "pizza", "donut", "cake", "chair", "couch",
    "potted plant", "bed", "dining table", "toilet", "TV", "laptop", "mouse", "remote", "keyboard",
    "cell phone", "microwave", "oven", "toaster", "sink", "refrigerator", "book", "clock", "vase",
    "scissors", "teddy bear", "hair drier", "toothbrush"
]

# Generate random colors for each class
CLASS_COLORS = {class_name: [random.randint(0, 255) for _ in range(3)] for class_name in COCO_CLASSES}

# Define input video path
video_path = r"C:\Users\CREATIVE IT PARK\Downloads\Video\aaa.mp4"
cap = cv2.VideoCapture(video_path)

# Get video properties
frame_width = int(cap.get(3))
frame_height = int(cap.get(4))
fps = int(cap.get(cv2.CAP_PROP_FPS))

# Define output video writer
output_path = r"C:\Users\CREATIVE IT PARK\PyCharmMiscProject\By Haroon\cOMMULATIVE COUNTING\aaaa.mp4"
fourcc = cv2.VideoWriter.fourcc(*'mp4v')
out = cv2.VideoWriter(output_path, fourcc, fps, (frame_width, frame_height))

# Persistent Object Tracking Data
seen_objects = set()  # Store unique object IDs to prevent re-counting
object_class_history = defaultdict(list)  # Store last N classifications per object
class_counts = defaultdict(int)  # Stores the total count per class

N_FRAMES = 5  # Number of frames to consider for classification smoothing

while cap.isOpened():
    ret, frame = cap.read()
    if not ret:
        break

    # Run YOLOv8 with tracking enabled
    results = model.track(frame, persist=True, conf=0.5)

    if results[0].boxes.id is not None:
        object_ids = results[0].boxes.id.cpu().numpy()
        class_ids = results[0].boxes.cls.cpu().numpy()

        for obj_id, class_id in zip(object_ids, class_ids):
            class_id = int(class_id)
            class_name = COCO_CLASSES[class_id] if class_id < len(COCO_CLASSES) else f"Class {class_id}"
            color = CLASS_COLORS.get(class_name, (0, 255, 0))

            # Maintain classification history for smoothing
            object_class_history[obj_id].append(class_name)
            if len(object_class_history[obj_id]) > N_FRAMES:
                object_class_history[obj_id].pop(0)

            # Assign the most frequent classification in the last N frames
            stable_class = Counter(object_class_history[obj_id]).most_common(1)[0][0]

            # Count the object only if it's seen for the first time
            if obj_id not in seen_objects:
                seen_objects.add(obj_id)  # Mark object as counted
                class_counts[stable_class] += 1

            # Draw bounding box and label
            box = results[0].boxes.xyxy[object_ids.tolist().index(obj_id)].cpu().numpy()
            x1, y1, x2, y2 = map(int, box)
            cv2.rectangle(frame, (x1, y1), (x2, y2), color, 2)
            label = f"ID: {int(obj_id)} {stable_class}"
            (w, h), _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 0.6, 2)
            cv2.rectangle(frame, (x1, y1 - h - 5), (x1 + w, y1), color, -1)
            cv2.putText(frame, label, (x1, y1 - 5),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 2)

    # Display persistent object count
    y_offset = 50
    for class_name, count in class_counts.items():
        label = f"{class_name}: {count}"
        (w, h), _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 1, 3)
        cv2.rectangle(frame, (40, y_offset - h - 5), (40 + w, y_offset), (0, 0, 0), -1)
        cv2.putText(frame, label, (50, y_offset),
                    cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 255, 255), 3)
        y_offset += 35

    # Write frame to output video
    out.write(frame)

    # Show frame in Google Colab
    # cv2.imshow(frame)

# Release resources
cap.release()
out.release()
cv2.destroyAllWindows()

print(f"Processed video saved at: {output_path}")







